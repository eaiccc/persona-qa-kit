#!/usr/bin/env python3
"""Generate the Codex CLI agent files from .claude/agents/*.md.

The Claude Code agent definitions are the single source of truth for what each
role is told. This script renders them into the shapes Codex reads:

    .codex/agents/<role>.toml        one custom agent per pipeline role
    adapters/codex/orchestrator.md   the root-session prompt (qa-orchestrator)

and never the other way round. Edit the .md files, then:

    python3 adapters/codex/generate.py          # write
    python3 adapters/codex/generate.py --check  # exit 1 if anything is stale

The test suite runs --check, so a definition edited without regenerating fails
CI rather than silently giving Codex an older prompt.

qa-orchestrator is not rendered as a custom agent. It dispatches the other
four, and in Codex the session that spawns subagents is the root session, so its
definition becomes that session's prompt instead.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(KIT / "tools"))

from pqa import roles  # noqa: E402

AGENTS_DIR = KIT / ".codex" / "agents"
ORCHESTRATOR = KIT / "adapters" / "codex" / "orchestrator.md"

HEADER = "# GENERATED by adapters/codex/generate.py from {source}. Do not edit.\n"


def codex_name(role: str) -> str:
    # Codex agent names are identifiers; the role table maps them back.
    return role.replace("-", "_")


def preamble(role: roles.Role) -> str:
    writes = ", ".join(f"`<run-dir>/{w}`" for w in role.writes)
    lines = [
        f"You are the `{role.name}` role of persona-qa-kit, running as a Codex subagent.",
        "",
        "The definition below was written for Claude Code. Its tool names map as follows:",
        "Write / Edit mean `apply_patch`; Bash means your shell tool; Read means reading",
        "the file from the shell (`cat`, `sed -n`). The run directory is named in the",
        "message that spawned you. Commands are run from the kit root (`./bin/pqa ...`).",
        "",
        f"You may write {writes} and nothing else.",
    ]
    if not role.shell:
        lines += [
            "Your shell is read-only: reading files and `./bin/pqa fingerprint|digest|drift|",
            "validate|gate|personas|inject|signals`. Write your output file with apply_patch.",
            "Digests cited in your output (session_digest, candidates_digest) come from",
            "`./bin/pqa digest <file>`.",
        ]
    if role.name == "user-agent":
        lines += [
            "",
            "Use the app through your browser tool, at the entrypoint in run.json. If no browser",
            "is available, that is what happened: record it and stop. Do not read the page",
            "source instead -- the persona cannot.",
            "",
            "Append each session record with `./bin/pqa record <run-dir> -`, the record as one",
            "JSON object on stdin (a quoted heredoc avoids shell quoting problems), rather than",
            "editing session.jsonl: it validates the record and refuses one in vocabulary the",
            "persona does not have, and when a persona re-injection is due its output carries",
            "the persona summary. Read that summary when it appears.",
        ]
    lines += [
        "",
        "These are enforced, not requested: a PreToolUse hook denies writes to the run's",
        "artifacts that would break it, and when you stop, a SubagentStop hook runs",
        f"`pqa gate --stage {role.stage}` and sends you back with its findings until it passes.",
        "",
        "---",
        "",
    ]
    return "\n".join(lines)


def render_agent(name: str) -> str:
    role = roles.lookup(name)
    definition = roles.load_definition(name)
    instructions = preamble(role) + definition.body
    if "'''" in instructions:
        raise SystemExit(f"{definition.path}: contains ''' and cannot be a TOML literal string")
    source = definition.path.relative_to(KIT).as_posix()
    return (
        HEADER.format(source=source)
        + f'name = "{codex_name(role.name)}"\n'
        + f"description = {_toml_string(definition.description)}\n"
        + f"developer_instructions = '''\n{instructions}'''\n"
    )


def render_orchestrator() -> str:
    definition = roles.load_definition("qa-orchestrator")
    dispatch = "\n".join(
        f"   {i}. `spawn_agent` with `agent_type: \"{codex_name(r)}\"`"
        + (" -- then read nothing it wrote; you do not read findings" if r != "user-agent" else "")
        for i, r in enumerate(roles.PIPELINE, start=1)
    )
    source = definition.path.relative_to(KIT).as_posix()
    return (
        f"<!-- GENERATED by adapters/codex/generate.py from {source}. Do not edit. -->\n\n"
        "# qa-orchestrator (Codex root session)\n\n"
        "You are the root session of a persona-qa-kit run under Codex CLI. Your role is\n"
        "`qa-orchestrator`, defined below. Where it says *dispatch*, do this:\n\n"
        f"{dispatch}\n\n"
        "Spawn them one at a time, in that order. Give each a message naming the run\n"
        "directory and nothing else of substance -- in particular, do not pass one role's\n"
        "conclusions to the next; each reads the artifacts itself. Do not fork your own\n"
        "context into them (`fork_turns: \"none\"`): a judging role that inherits the\n"
        "transcript of the run it is judging is the self-certification failure in\n"
        "DESIGN.md section 1. Wait for each to finish, then close it before spawning the\n"
        "next.\n\n"
        "Each subagent's stop is gated by a SubagentStop hook at that role's stage, and\n"
        "your own stop by the full gate. Environment variables you export do not reach\n"
        "the hooks; they find the run that `pqa seal` marked active (runs/.active), so\n"
        "seal before dispatching anyone, and do not seal a second run in this checkout\n"
        "while this one is in progress.\n\n"
        "---\n\n"
        + definition.body
    )


def _toml_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def outputs() -> dict[Path, str]:
    files = {AGENTS_DIR / f"{codex_name(r)}.toml": render_agent(r) for r in roles.PIPELINE}
    files[ORCHESTRATOR] = render_orchestrator()
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    args = parser.parse_args(argv)

    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(KIT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    if args.check:
        if stale:
            print("stale (run python3 adapters/codex/generate.py): " + ", ".join(stale),
                  file=sys.stderr)
            return 1
        print("codex agent files are up to date")
        return 0
    print("wrote " + (", ".join(stale) if stale else "nothing (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
